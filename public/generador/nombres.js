// Una persona al azar: {nombre, apellido(s), completo, cultura}. g = 'M' o 'F' (al azar si falta).
function personaAlAzar(g, cultura) {
  const d = n => { const u = new Uint32Array(1); crypto.getRandomValues(u); return 1 + (u[0] % n); };
  const uno = xs => xs[d(xs.length) - 1];
  if (!cultura) {
    const total = NOMBRES_REALES.reduce((s, c) => s + c.peso, 0);
    let r = d(total);
    cultura = NOMBRES_REALES.find(c => (r -= c.peso) <= 0);
  }
  g = g || (d(2) === 1 ? 'M' : 'F');
  const ape = () => { const x = uno(cultura.apellidos); return Array.isArray(x) ? x[g === 'F' ? 1 : 0] : x; };
  const nombre = uno(cultura[g]);
  let apellido = ape();
  if (cultura.dosApellidos) { let otro = ape(); while (otro === apellido) otro = ape(); apellido += ' ' + otro; }
  const completo = cultura.apellidoPrimero ? `${apellido} ${nombre}` : `${nombre} ${apellido}`;
  return { g, nombre, apellido, completo, cultura };
}

